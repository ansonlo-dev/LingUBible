// 這份清單是「人手策展」的：它由 GitHub commit 歷史整理而來，但刻意**不**逐條照抄。
// 純技術性、內部重構、部署設定、除錯日誌、暫存提交等對一般使用者沒有意義的改動一律略過；
// 同一天內針對同一件事的多個 commit 會合併成單一條目，以使用者看得懂的語言描述。
//
// 新增條目時：
//   1. 放在檔案最前面（本檔以「新到舊」排列）。
//   2. id 用 `YYYY-MM-DD-n`，同日條目 n 由 1 遞增，之後不要再改（網址錨點會用到）。
//   3. 三個語言版本都要填；desc 為選填，只在標題不足以說清楚時才補。

export type ChangelogType =
  | 'feature' // 新功能
  | 'improvement' // 體驗優化 / 介面調整
  | 'fix' // 問題修復
  | 'performance' // 效能與載入速度
  | 'data' // 課程 / 講師 / 時間表等資料更新
  | 'security'; // 帳戶安全與私隱

